#!/usr/bin/env python3
"""Writes or checks THIRD_PARTY_NOTICES.md from the locked dependency graph.

Every crate the editor's Linux and Windows executables are built from, through
normal dependencies, is listed with the licence it is used under, and the
licence texts and notices those licences ask to be kept with the editor are
copied from the crates themselves. `--check` fails when the file is not what
the lockfile gives, or when a crate is used under a licence it ships no text
for.
"""
# Copyright (c) 2026 Seraphina Studios. SPDX-License-Identifier: MIT
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT_PACKAGE = 'tilewright-editor'
TARGETS = {'x86_64-unknown-linux-gnu': 'Linux', 'x86_64-pc-windows-msvc': 'Windows'}
OUTPUT = 'THIRD_PARTY_NOTICES.md'
# Crates by Seraphina Studios, under the editor's own licence and copyright.
FIRST_PARTY = 'https://github.com/seraphinastudios/'
# Of a crate's choices, the first it ships the text of; Apache-2.0 needs no
# copy of a crate's own, as its text is kept once below.
PREFERENCE = ['MIT', 'Apache-2.0', 'Zlib', 'ISC', 'Unicode-3.0', 'BSD-3-Clause', 'BSD-2-Clause', 'BSL-1.0']
SHARED_TEXT = {'Apache-2.0'}
# The fonts egui draws with, each under its own licence, kept from the font
# crate's own files. Its Noto Emoji font (OFL-1.1) is not built.
FONT_CRATE = 'epaint_default_fonts'
FONTS = [
    ('Hack', 'fonts/Hack-Regular.txt'),
    ('emoji-icon-font', 'fonts/emoji-icon-font-mit-license.txt'),
    ('Ubuntu Font Licence 1.0 (Ubuntu Light)', 'fonts/UFL.txt'),
]
FONT_TERMS = {'OFL-1.1', 'Ubuntu-font-1.0'}
LICENCE_FILE = re.compile(r'^(licen[cs]e|copying|copyright|notice|unlicense)', re.IGNORECASE)
# Statements kept with a crate's licence text, whatever it is used under.
STATEMENT_FILE = re.compile(r'^(copyright|notice)', re.IGNORECASE)

HEADER = """# Third-party notices

The editor source is MIT (`LICENSE`). This file is generated by
`tools/third-party-notices.py` from `Cargo.lock`, and `tools/validate.sh`
fails when it is out of date. It lists every crate the editor's Linux and
Windows executables are built from through normal dependencies, the licence
each is used under, and the licence texts and notices those licences ask to
be kept with the editor, copied from the crates themselves. `cargo-deny`
checks the licences against `deny.toml`, and each release's CycloneDX SBOM
records the exact graph.

Where a crate offers a choice, it is used under the first of MIT,
Apache-2.0, Zlib, ISC and the BSD licences that it ships the text of; the
Apache License 2.0, which asks for no copy of a crate's own, is kept once at
the end.

Authored content opened by the editor is not part of this software and retains
its own license and attribution.

## Fonts

`epaint_default_fonts` declares `(MIT OR Apache-2.0) AND OFL-1.1 AND
Ubuntu-font-1.0`. The editor compiles in three of its fonts, each under its
own license:

- `Hack-Regular.ttf`: Hack, MIT, with the Bitstream Vera License of the font
  it derives from.
- `Ubuntu-Light.ttf`: Ubuntu Font Licence 1.0.
- `egui-icons.ttf`, a subset of emoji-icon-font: MIT.

Its Noto Emoji font (SIL Open Font License 1.1) and the whole emoji-icon-font
are built only with its `monochrome_emoji_fonts` feature, which the editor
does not enable, so neither is shipped.
"""


class NoticeError(Exception):
    pass


# What a licence's text says, in words no other licence here uses, matched
# with whitespace collapsed.
MARKERS = [
    ('Unicode-3.0', ['UNICODE LICENSE']),
    ('Unicode-3.0', ['Unicode, Inc.']),
    # The licence itself, not a notice pointing to it.
    ('Apache-2.0', ['Apache License', 'Version 2.0', 'TERMS AND CONDITIONS FOR USE, REPRODUCTION, AND DISTRIBUTION']),
    ('Apache-2.0 WITH LLVM-exception', ['LLVM Exceptions']),
    ('GPL', ['GNU GENERAL PUBLIC LICENSE']),
    ('MIT', ['to any person obtaining a copy of this software']),
    ('Zlib', ["provided 'as-is'", 'must not be misrepresented']),
    ('ISC', ['Permission to use, copy, modify, and/or distribute this software for any purpose']),
    ('BSL-1.0', ['Boost Software License']),
    ('BSD-3-Clause', ['Redistribution and use in source and binary forms', 'Neither the name']),
    ('BSD-2-Clause', ['Redistribution and use in source and binary forms']),
    ('Unlicense', ['This is free and unencumbered software']),
]


def classify(text):
    """The licences a file's text holds, by their wording."""
    words = ' '.join(text.split())
    found = {licence for licence, markers in MARKERS if all(marker in words for marker in markers)}
    if 'BSD-3-Clause' in found:
        found.discard('BSD-2-Clause')
    return found


def terms(expression):
    """An SPDX expression's AND terms, each a list of its OR choices."""
    expression = expression.replace('/', ' OR ')
    groups, depth, current = [], 0, ''
    for token in re.findall(r'\(|\)|[^\s()]+', expression):
        if token == '(':
            depth += 1
        elif token == ')':
            depth -= 1
        elif token == 'AND' and depth == 0:
            groups.append(current)
            current = ''
            continue
        current += f' {token}'
    groups.append(current)
    result = []
    for group in groups:
        choices = [choice.strip() for choice in re.split(r'\bOR\b', group.replace('(', ' ').replace(')', ' '))]
        result.append([choice for choice in choices if choice])
    return result


def choose(expression, shipped):
    """The licences a crate is used under: of each AND term, the first
    preferred choice it ships the text of, or that needs none."""
    used = []
    for choices in terms(expression):
        usable = [licence for licence in PREFERENCE if licence in choices and (licence in SHARED_TEXT or licence in shipped)]
        if not usable:
            raise NoticeError(f'no usable licence among {" OR ".join(choices)} (texts shipped: {", ".join(sorted(shipped)) or "none"})')
        used.append(usable[0])
    return used


def normalized(text):
    lines = [line.expandtabs(8).rstrip() for line in text.replace('\r\n', '\n').replace('\r', '\n').split('\n')]
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()
    return '\n'.join(lines)


def fenced(text):
    longest = max((len(run) for run in re.findall(r'`+', text)), default=0)
    fence = '`' * max(3, longest + 1)
    return f'{fence}text\n{text}\n{fence}\n'


def run(arguments, root):
    return subprocess.run(arguments, cwd=root, check=True, capture_output=True, text=True).stdout


def shipped_crates(root):
    """(name, version) of every crate in each target's normal graph."""
    graph = {}
    for target, platform in TARGETS.items():
        tree = run(['cargo', 'tree', '--locked', '--offline', '--package', ROOT_PACKAGE, '--edges', 'normal',
                    '--target', target, '--prefix', 'none', '--format', '{p}'], root)
        for line in tree.splitlines():
            fields = line.split()
            if len(fields) >= 2 and fields[1].startswith('v'):
                graph.setdefault((fields[0], fields[1][1:]), set()).add(platform)
    return graph


def crate_files(directory):
    files = {}
    for path in sorted(directory.iterdir(), key=lambda path: path.name):
        if path.is_file() and LICENCE_FILE.match(path.name):
            files[path.name] = normalized(path.read_text(encoding='utf-8', errors='replace'))
    return files


def render(root):
    metadata = json.loads(run(['cargo', 'metadata', '--locked', '--offline', '--format-version', '1'], root))
    packages = {(package['name'], package['version']): package for package in metadata['packages']}
    members = set(metadata['workspace_members'])
    rows, bundles, shared, fonts = [], {}, {}, []
    for key, platforms in sorted(shipped_crates(root).items()):
        package = packages.get(key)
        if package is None:
            raise NoticeError(f'{key[0]} {key[1]} is in the tree but not in the metadata')
        if package['id'] in members:
            continue
        name, version = key
        built = ', '.join(platform for platform in TARGETS.values() if platform in platforms)
        expression = package.get('license') or ''
        if (package.get('repository') or '').startswith(FIRST_PARTY):
            rows.append((name, version, built, f'{expression}, by Seraphina Studios, as the editor'))
            continue
        if not expression:
            raise NoticeError(f'{name} {version} declares no licence expression')
        directory = Path(package['manifest_path']).parent
        files = crate_files(directory)
        kinds = {file: classify(text) for file, text in files.items()}
        texts = set().union(*kinds.values())
        try:
            if name == FONT_CRATE:
                code = [choices for choices in terms(expression) if not FONT_TERMS.intersection(choices)]
                used = choose(' AND '.join(' OR '.join(choices) for choices in code), texts)
                for title, file in FONTS:
                    path = directory / file
                    if not path.is_file():
                        raise NoticeError(f'its font licence {file} is missing')
                    fonts.append((title, normalized(path.read_text(encoding='utf-8'))))
                used_text = ' AND '.join(used + ['font licences above'])
            else:
                used = choose(expression, texts)
                used_text = ' AND '.join(used)
        except NoticeError as error:
            raise NoticeError(f'{name} {version} ({expression}): {error}') from None
        rows.append((name, version, built, used_text))
        own = set(used) - SHARED_TEXT
        kept = [(file, text) for file, text in files.items() if kinds[file] & own or STATEMENT_FILE.match(file)]
        if kept:
            bundle = '\n\n'.join(text for _, text in kept)
            bundles.setdefault(bundle, []).append(f'{name} {version}')
        for licence in used:
            if licence in SHARED_TEXT:
                shared.setdefault(licence, []).append(f'{name} {version}')
                for file, text in files.items():
                    if kinds[file] == {licence}:
                        shared.setdefault(f'{licence} text', []).append(text)
    out = [HEADER]
    for title, text in fonts:
        out.append(f'\n### {title}\n\n{fenced(text)}')
    out.append('\n## Crates\n\n| Crate | Version | Built for | Used under |\n| --- | --- | --- | --- |\n')
    for name, version, built, used in rows:
        out.append(f'| `{name}` | {version} | {built} | {used} |\n')
    out.append('\n## Licence texts and notices\n\nEach crate\'s own copy, with its copyright notice; crates whose texts are\nthe same share one.\n')
    for bundle, crates in sorted(bundles.items(), key=lambda item: item[1][0]):
        out.append(f'\n### {", ".join(crates)}\n\n{fenced(bundle)}')
    for licence in sorted(SHARED_TEXT):
        crates = shared.get(licence, [])
        if not crates:
            continue
        texts = shared.get(f'{licence} text', [])
        if not texts:
            raise NoticeError(f'no crate ships the {licence} text')
        out.append(f'\n## {licence}\n\nUsed by: {", ".join(f"`{crate}`" for crate in crates)}.\n\n{fenced(texts[0])}')
    return ''.join(out)


def main(arguments):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument('--check', action='store_true', help='fail when the file is out of date')
    options = parser.parse_args(arguments)
    try:
        text = render(options.root)
    except (NoticeError, subprocess.CalledProcessError, OSError) as error:
        detail = getattr(error, 'stderr', '') or ''
        print(f'cannot make the third-party notices: {error} {detail}'.strip(), file=sys.stderr)
        return 1
    path = options.root / OUTPUT
    if options.check:
        if not path.is_file() or path.read_text(encoding='utf-8') != text:
            print(f'{OUTPUT} is out of date; run tools/third-party-notices.py', file=sys.stderr)
            return 1
        return 0
    path.write_text(text, encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
